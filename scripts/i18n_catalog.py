def ja_to_key() -> dict[str, str]:
    mapping: dict[str, str] = {}
    collisions: list[str] = []
    for key, (ja, _en) in STRINGS.items():
        if ja in mapping and mapping[ja] != key:
            collisions.append(f"{ja!r}: {mapping[ja]} vs {key}")
        else:
            mapping[ja] = key
    if collisions:
        raise ValueError("Japanese collision:\n" + "\n".join(collisions))
    return mapping
